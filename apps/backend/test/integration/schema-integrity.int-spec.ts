import { DataSource } from 'typeorm';

import { ADDED_FOREIGN_KEYS, INTENTIONALLY_UNCONSTRAINED } from './support/referential-integrity';

interface PgColumn {
  table_name: string;
  column_name: string;
  data_type: string;
  udt_name: string;
  is_nullable: 'YES' | 'NO';
  column_default: string | null;
}

/**
 * Introspects the REAL PostgreSQL catalogs (information_schema /
 * pg_constraint / pg_indexes) and checks them against TypeORM's own
 * entity metadata and against the specific invariants the application
 * relies on. Nothing here duplicates schema logic: the expectations
 * about entities come from the metadata itself, the expectations about
 * invariants are the named constraints/indexes the migrations create.
 */
describe('Real PostgreSQL schema integrity', () => {
  let ds: DataSource;
  let columns: Map<string, PgColumn>;

  const q = <T = any>(sql: string, params: unknown[] = []): Promise<T[]> => ds.query(sql, params);

  beforeAll(async () => {
    const { AppDataSource } = await import('../../src/database/data-source');
    ds = AppDataSource;
    if (!ds.isInitialized) await ds.initialize();
    const rows = await q<PgColumn>(
      "SELECT table_name, column_name, data_type, udt_name, is_nullable, column_default FROM information_schema.columns WHERE table_schema = 'public'",
    );
    columns = new Map(rows.map((c) => [`${c.table_name}.${c.column_name}`, c]));
  });

  afterAll(async () => {
    if (ds?.isInitialized) await ds.destroy();
  });

  const expectedPgType: Record<string, string[]> = {
    uuid: ['uuid'],
    varchar: ['character varying'],
    text: ['text'],
    bigint: ['bigint'],
    int: ['integer'],
    integer: ['integer'],
    smallint: ['smallint'],
    boolean: ['boolean'],
    jsonb: ['jsonb'],
    timestamptz: ['timestamp with time zone'],
    timestamp: ['timestamp with time zone'],
    numeric: ['numeric'],
    'double precision': ['double precision'],
    enum: ['USER-DEFINED'],
  };

  it('every entity column maps to a real column with the same name, compatible type, and matching nullability', () => {
    const problems: string[] = [];
    for (const meta of ds.entityMetadatas) {
      for (const col of meta.columns) {
        const db = columns.get(`${meta.tableName}.${col.databaseName}`);
        if (!db) {
          problems.push(`${meta.targetName}.${col.propertyName}: column "${col.databaseName}" does not exist in table "${meta.tableName}"`);
          continue;
        }
        const declared = String(col.type);
        const allowed = expectedPgType[declared];
        if (!allowed) problems.push(`${meta.targetName}.${col.propertyName}: unrecognised declared type "${declared}"`);
        else if (!allowed.includes(db.data_type)) {
          problems.push(`${meta.targetName}.${col.propertyName}: declared ${declared} but PostgreSQL has ${db.data_type}`);
        }
        const dbNullable = db.is_nullable === 'YES';
        if (col.isNullable !== dbNullable && !col.isPrimary) {
          problems.push(`${meta.targetName}.${col.propertyName}: entity nullable=${col.isNullable} but PostgreSQL nullable=${dbNullable}`);
        }
      }
    }
    expect(problems).toEqual([]);
  });

  it('no NOT NULL / no-default column exists in an entity table that the entity does not map (an INSERT would fail at runtime)', () => {
    const mapped = new Set(ds.entityMetadatas.flatMap((m) => m.columns.map((c) => `${m.tableName}.${c.databaseName}`)));
    const tables = new Set(ds.entityMetadatas.map((m) => m.tableName));
    const orphans = [...columns.values()]
      .filter((c) => tables.has(c.table_name) && !mapped.has(`${c.table_name}.${c.column_name}`))
      .filter((c) => c.is_nullable === 'NO' && c.column_default === null)
      .map((c) => `${c.table_name}.${c.column_name}`);
    expect(orphans).toEqual([]);
  });

  it('every entity table has a primary key, and BaseEntity tables use uuid ids generated by the database plus timestamptz audit/soft-delete columns', async () => {
    const withoutPk = await q(
      `SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE n.nspname = 'public' AND c.relkind = 'r'
         AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = c.oid AND k.contype = 'p')`,
    );
    expect(withoutPk).toEqual([]);

    for (const meta of ds.entityMetadatas) {
      const id = columns.get(`${meta.tableName}.id`);
      if (!id) continue;
      expect(id.data_type).toBe('uuid');
      expect(id.column_default).toBe('uuid_generate_v4()');
      for (const audit of ['created_at', 'updated_at']) {
        expect(columns.get(`${meta.tableName}.${audit}`)?.data_type).toBe('timestamp with time zone');
      }
      const deleted = columns.get(`${meta.tableName}.deleted_at`);
      if (deleted) {
        expect(deleted.data_type).toBe('timestamp with time zone');
        expect(deleted.is_nullable).toBe('YES');
      }
    }
  });

  it('EVERY *_minor monetary column is bigint (never int/numeric/float), and points columns are integer', () => {
    const wrong = [...columns.values()]
      .filter((c) => /_minor(_snapshot)?$|_minor_used$/.test(c.column_name) && c.data_type !== 'bigint')
      .map((c) => `${c.table_name}.${c.column_name}:${c.data_type}`);
    expect(wrong).toEqual([]);
    expect(columns.get('loyalty_points_transactions.points_delta')?.data_type).toBe('integer');
    expect(columns.get('wallet_transactions.amount_delta_minor')?.data_type).toBe('bigint');
    expect(columns.get('financial_events.amount_minor')?.data_type).toBe('bigint');
  });

  it('no timestamp column is timezone-naive, and every NOT NULL boolean has a default', () => {
    const naive = [...columns.values()].filter((c) => c.data_type === 'timestamp without time zone');
    expect(naive).toEqual([]);
    const boolNoDefault = [...columns.values()]
      .filter((c) => c.data_type === 'boolean' && c.is_nullable === 'NO' && c.column_default === null)
      .map((c) => `${c.table_name}.${c.column_name}`);
    expect(boolNoDefault).toEqual([]);
    expect(columns.get('offer_consumptions.is_reversed')?.column_default).toBe('false');
  });

  it('every foreign key TypeORM metadata expects exists as a real FK constraint, except the documented deliberately-unconstrained ones', async () => {
    const fks = await q<{ tbl: string; cols: string[] }>(
      `SELECT c.conrelid::regclass::text AS tbl,
              array(SELECT a.attname::text FROM unnest(c.conkey) k JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k) AS cols
       FROM pg_constraint c WHERE c.contype = 'f' AND c.connamespace = 'public'::regnamespace`,
    );
    const real = new Set(fks.map((f) => `${f.tbl}.${f.cols.join(',')}`));
    const missing: string[] = [];
    for (const meta of ds.entityMetadatas) {
      for (const fk of meta.foreignKeys) {
        const key = `${meta.tableName}.${fk.columnNames.join(',')}`;
        if (!real.has(key)) missing.push(key);
      }
    }
    // Group 7A closed every relation-declared gap: any entity relation without a real FK now fails this test.
    expect(missing.sort()).toEqual([]);
    // Critical FKs are really enforced by PostgreSQL:
    for (const key of [
      'orders.customer_id',
      'order_vendor_segments.order_id',
      'order_items.order_vendor_segment_id',
      'payments.order_id',
      'deliveries.order_id',
      'favorites.customer_id',
      'favorites.vendor_id',
      'offer_consumptions.offer_id',
    ]) {
      expect(real.has(key)).toBe(true);
    }
  });

  it('every uuid *_id column is either a real foreign key or a documented, reasoned exception — a new FK-less reference fails this test', async () => {
    const rows = await q<{ ref: string }>(
      `SELECT c.table_name || '.' || c.column_name AS ref
       FROM information_schema.columns c
       WHERE c.table_schema = 'public' AND c.data_type = 'uuid' AND c.column_name <> 'id'
         AND c.table_name <> 'migrations'
         AND NOT EXISTS (
           SELECT 1 FROM pg_constraint k JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = ANY (k.conkey)
           WHERE k.contype = 'f' AND k.conrelid = quote_ident(c.table_name)::regclass AND a.attname = c.column_name)
       ORDER BY 1`,
    );
    expect(rows.map((r) => r.ref)).toEqual(INTENTIONALLY_UNCONSTRAINED.map((e) => e.ref).sort());
    for (const entry of INTENTIONALLY_UNCONSTRAINED) expect(entry.reason.length).toBeGreaterThan(40);
    // A column listed as an exception must not ALSO be a documented-added FK.
    const added = new Set(ADDED_FOREIGN_KEYS.map((f) => `${f.table}.${f.column}`));
    for (const entry of INTENTIONALLY_UNCONSTRAINED) expect(added.has(entry.ref)).toBe(false);
  });

  it('TypeORM relation metadata and PostgreSQL agree on every foreign key\'s ON DELETE behaviour', async () => {
    const actions: Record<string, string> = { a: 'NO ACTION', r: 'RESTRICT', c: 'CASCADE', n: 'SET NULL', d: 'SET DEFAULT' };
    const fks = await q<{ tbl: string; col: string; action: string }>(
      `SELECT c.conrelid::regclass::text AS tbl, a.attname::text AS col, c.confdeltype::text AS action
       FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
       WHERE c.contype = 'f' AND c.connamespace = 'public'::regnamespace`,
    );
    const real = new Map(fks.map((f) => [`${f.tbl}.${f.col}`, actions[f.action]]));
    const disagreements: string[] = [];
    for (const meta of ds.entityMetadatas) {
      for (const fk of meta.foreignKeys) {
        const key = `${meta.tableName}.${fk.columnNames[0]}`;
        const db = real.get(key);
        if (!db) continue; // absence is covered by the FK-presence test above
        const declared = (fk.onDelete ?? 'NO ACTION').toUpperCase();
        if (declared !== db) disagreements.push(`${key}: entity=${declared} database=${db}`);
      }
    }
    expect(disagreements).toEqual([]);
  });

  it('the idempotency / uniqueness invariants the application depends on are real UNIQUE indexes (with the right predicates)', async () => {
    const idx = await q<{ tablename: string; indexname: string; indexdef: string }>(
      "SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' AND indexdef LIKE 'CREATE UNIQUE%'",
    );
    const defs = idx.map((i) => i.indexdef.replace(/\s+/g, ' '));
    const has = (fragment: string) => defs.some((d) => d.includes(fragment));

    expect(has('ON public.wallet_transactions USING btree (idempotency_key)')).toBe(true);
    expect(has('ON public.financial_events USING btree (idempotency_key)')).toBe(true);
    expect(has('ON public.loyalty_points_transactions USING btree (idempotency_key) WHERE (idempotency_key IS NOT NULL)')).toBe(true);
    expect(has("ON public.loyalty_points_transactions USING btree (order_id) WHERE ((type)::text = 'EARNING'::text)")).toBe(true);
    expect(has('ON public.driver_cash_remainders USING btree (order_id)')).toBe(true);
    expect(has('ON public.failed_delivery_resolutions USING btree (order_id)')).toBe(true);
    expect(has('ON public.favorites USING btree (customer_id, vendor_id)')).toBe(true);
    expect(has('ON public.deliveries USING btree (order_id)')).toBe(true);
    expect(has('ON public.users USING btree (phone)')).toBe(true);
    expect(has("ON public.carts USING btree (customer_id) WHERE (status = 'ACTIVE'::carts_status_enum)")).toBe(true);
    expect(has('ON public.offer_consumptions USING btree (order_item_id) WHERE (order_item_id IS NOT NULL)')).toBe(true);
    expect(has('ON public.offer_consumptions USING btree (order_vendor_segment_id) WHERE (order_vendor_segment_id IS NOT NULL)')).toBe(true);
    expect(has('ON public.vendor_ratings USING btree (customer_id, order_vendor_segment_id)')).toBe(true);
    expect(has('ON public.product_ratings USING btree (customer_id, order_item_id)')).toBe(true);
    expect(has('ON public.driver_ratings USING btree (customer_id, delivery_id)')).toBe(true);
    expect(has('ON public.order_item_weight_records USING btree (order_item_id)')).toBe(true);
    expect(has('ON public.ad_hoc_purchase_records USING btree (order_item_id)')).toBe(true);
  });

  it('the money/ledger/state CHECK constraints exist in PostgreSQL', async () => {
    const rows = await q<{ conname: string }>(
      "SELECT conname FROM pg_constraint WHERE contype = 'c' AND connamespace = 'public'::regnamespace",
    );
    const names = new Set(rows.map((r) => r.conname));
    for (const name of [
      'chk_wallet_amount_nonzero',
      'chk_wallet_transaction_type',
      'chk_loyalty_points_delta_nonzero',
      'chk_loyalty_points_type',
      'chk_driver_cash_remainder_amount_positive',
      'chk_driver_cash_remainder_status',
      'chk_failed_delivery_resolution_outcome',
      'chk_failed_delivery_resolution_refund_amount',
      'chk_offer_consumptions_quantity_positive',
      'chk_offer_consumptions_unit',
      'chk_offers_mechanism_fields',
      'chk_offers_percentage_bounds',
      'chk_offers_validity_window',
      'chk_payments_pending_refund_status',
      'chk_payments_pending_refund_minor',
    ]) {
      expect(names).toContain(name);
    }
  });

  it('jsonb columns hold the snapshot/breakdown payloads the domain expects', () => {
    const jsonb = [...columns.values()].filter((c) => c.data_type === 'jsonb').map((c) => `${c.table_name}.${c.column_name}`);
    expect(jsonb).toEqual(expect.arrayContaining(['orders.delivery_address_snapshot', 'orders.delivery_fee_breakdown_snapshot']));
  });
});
